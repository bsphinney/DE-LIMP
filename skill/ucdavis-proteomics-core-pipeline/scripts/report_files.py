def record_skill_doc(path, writer):
    """Record that the skill (`writer`: session.py init, session_docs.py, make_podcast.py link)
    has just written `path` -- a session document at the session's root -- as it is now. -> None,
    or why it could not be recorded (said on stderr: the document is then judged by its marker
    alone, as before 2.14.2)."""
    session = os.path.dirname(os.path.abspath(path))
    rec_path = os.path.join(session, SKILL_DOCS_RECORD)
    try:
        rec, bad = _read_json(rec_path)
        docs = (rec or {}).get("docs") if isinstance((rec or {}).get("docs"), dict) else {}
        docs[os.path.basename(path)] = {"sha256": _sha256(path), "writer": writer, "at": _now()}
        os.makedirs(os.path.dirname(rec_path), exist_ok=True)
        _write_json(rec_path, {"schema": SKILL_DOCS_SCHEMA, "docs": docs})
    except OSError as e:
        why = f"{SKILL_DOCS_RECORD} not written ({e.strerror or e})"
        import sys
        sys.stderr.write(f"[report_files] WARNING: {os.path.basename(path)}: {why}: whether it "
                         "is edited later is judged by its marker alone\n")
        return why
    return None


def recorded_skill_doc(path):
    """The sha256 the skill recorded when it last wrote `path` (record_skill_doc), or None: no
    record (a session from before 2.14.2, a copy without logs/, or none ever written)."""
    rec, _bad = _read_json(os.path.join(os.path.dirname(os.path.abspath(path)),
                                        SKILL_DOCS_RECORD))
    docs = (rec or {}).get("docs")
    one = docs.get(os.path.basename(path)) if isinstance(docs, dict) else None
    return one.get("sha256") if isinstance(one, dict) else None


def is_untouched_starter(text):
    """`text` is session.py init's starter README.md and nothing else -- its lines in order: the
    title, the date, "Status: in progress", a re-analysis line (optional), the layout line, the
    skill's marker (2.14.2; optional). One more line of any kind is someone's own."""
    want = [lambda x: x.startswith("# ") and len(x) > 2,
            lambda x: x.startswith("- Date: "),
            lambda x: x == "- Status: in progress",
            ("optional", lambda x: x.startswith("- **Re-analysis of:** ")),
            lambda x: x == STARTER_README_LAYOUT,
            ("optional", lambda x: x == SKILL_DOC_MARKER)]
    lines = [ln.rstrip() for ln in text.splitlines() if ln.strip()]
    i = 0
    for rule in want:
        optional, test = (True, rule[1]) if isinstance(rule, tuple) else (False, rule)
        if i < len(lines) and test(lines[i]):
            i += 1
        elif not optional:
            return False
    return i == len(lines)


def is_starter_readme(path):
    """`path` is session.py init's starter README.md, which finalize replaces."""
    try:
        with open(path, encoding="utf-8", errors="replace") as fh:
            return STARTER_README_SIGN in fh.read()
    except OSError:
        return False


def is_skill_doc(path):
    """`path` is one of the skill's own session documents, which finalize and `session.py docs`
    write again: as the skill last wrote it (its sha256 in SKILL_DOCS_RECORD), or -- with no
    record -- an untouched starter README, or a document with SKILL_DOC_MARKER (or, before
    2.14.2, LEGACY_DOC_SIGNS). One the skill wrote and someone then edited is not (L5b review M1).
    False for a file that is not there or cannot be read."""
    try:
        with open(path, encoding="utf-8", errors="replace") as fh:
            text = fh.read()
    except OSError:
        return False
    recorded = recorded_skill_doc(path)
    if recorded:
        try:
            return _sha256(path) == recorded
        except OSError:
            return False
    if STARTER_README_SIGN in text:
        return is_untouched_starter(text)
    return SKILL_DOC_MARKER in text or any(s in text for s in LEGACY_DOC_SIGNS)


def skill_doc_targets(session_dir):
    """{"README.md": path, "README.html": path, "AGENTS.md": path}: where the skill writes each
    document -- the name itself, unless a file there was written by hand, then its twin
    (README.skill.md, ...) -- and "kept": [the names written by hand, kept as they are]. Only a
    file counts as written by hand: anything else there (a folder) is not a document, and the
    skill's write to that name fails and says so, as before."""
    out, kept = {}, []
    for name in SKILL_DOCS:
        path = os.path.join(session_dir, name)
        if os.path.isfile(path) and not is_skill_doc(path):
            kept.append(name)
            out[name] = os.path.join(session_dir, SKILL_DOC_TWIN[name])
        else:
            out[name] = path
    out["kept"] = kept
    return out


