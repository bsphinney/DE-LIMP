def finalized_record(output_dir):
    """-> (record, why): output/FINALIZED.json when it is session.py finalize's stamp, else
    (None, why it is not there or not usable). A stamp that does not name every required output
    (STAMP_REQUIRED, by checksum or "[SKIPPED] <reason>") is not finalize's: one with `outputs: {}`
    -- written by hand, or by an old test fixture -- could never go stale (L5b review N2)."""
    path = os.path.join(output_dir, FINALIZED_RECORD)
    rec, bad = _read_json(path)
    if bad:
        return None, bad
    if rec is None:
        return None, NO_STAMP_WHY
    if rec.get("schema") != FINALIZED_SCHEMA:
        return None, f"output/FINALIZED.json is not a {FINALIZED_SCHEMA} stamp"
    outputs = rec.get("outputs") if isinstance(rec.get("outputs"), dict) else {}
    lacking = [rel for rel in STAMP_REQUIRED if not isinstance(outputs.get(rel), str)]
    if lacking:
        return None, ("output/FINALIZED.json is not a stamp session.py finalize wrote: it "
                      + ("names none of its outputs" if not outputs else
                         "does not name " + ", ".join(lacking))
                      + " -- run session.py finalize")
    return rec, None


def stamp_drift(session_dir, rec):
    """The stamped outputs that changed (or went) since finalize stamped them: [relative path]."""
    changed = []
    for rel, val in sorted(((rec or {}).get("outputs") or {}).items()):
        if not (isinstance(val, str) and len(val) == 64 and not val.startswith("[")):
            continue                                 # a [SKIPPED] entry: nothing to compare
        path = os.path.join(session_dir, rel)
        try:
            same = _sha256(path) == val
        except OSError:
            same = False
        if not same:
            changed.append(rel)
    return changed


def _word(a):
    """One word of a command line as the user types it: quoted, except a <placeholder> for what
    the session has no record of (make_deposit.bundle_command), which the user fills in."""
    return a if (a.startswith("<") and a.endswith(">")) else shlex.quote(a)


def shell_line(cmd, session, raws):
    """`cmd` ([python, scripts/<tool>.py, args...], as finalize runs it) as the line a refusal
    prints: `python3 scripts/<tool>.py ...`. The raw files after --raw are read from the session's
    input/raw_files.txt by the shell when there are more than five (and it lists them), so a long
    cohort does not fill the message. One definition, for the Methods and the bundle commands."""
    args = list(cmd[2:])
    raws = list(raws or [])
    head = f"python3 scripts/{os.path.basename(cmd[1])}"
    if "--raw" not in args or not raws:
        return " ".join([head] + [_word(a) for a in args])
    i = args.index("--raw") + 1
    listed = os.path.join(session, "input", "raw_files.txt")
    if len(raws) > 5 and os.path.isfile(listed) and not any(c.isspace() for r in raws for c in r):
        raw_part = f"$(grep -v '^#' {shlex.quote(listed)})"
    else:
        raw_part = " ".join(shlex.quote(r) for r in raws)
    before, rest = args[:i], args[i + len(raws):]
    return " ".join([head] + [_word(a) for a in before] + [raw_part] + [_word(a) for a in rest])


def _methods_command(session, out_md):
    """make_methods.py's command line for this session, exactly as finalize would run it
    (make_deposit.methods_command, the one definition), or None when the session cannot give it
    (no raw-file list). A long raw list is read from input/raw_files.txt by the shell. Imported
    here, not at the top: a partial copy of scripts/ still catalogues (the module docstring)."""
    try:
        import make_deposit
        f = make_deposit.gather(session)
        cmd = make_deposit.methods_command(f, out_md)
    except Exception:                            # noqa: BLE001 -- a hint only: the caller
        return None                              # falls back to the step's own words
    return shell_line(cmd, session, f["raws"])


def _bundle_command(session):
    """provenance.py's command line for this session, exactly as finalize runs it when it builds
    the bundle (make_deposit.bundle_command, the one definition): every flag from the session's
    records, a <placeholder> for one it has no record of. None when it cannot be worked out."""
    try:
        import make_deposit
        f = make_deposit.gather(session)
        cmd, _missing, _unnamed = make_deposit.bundle_command(f)
        raws = make_deposit.bundle_raws(f)
    except Exception:                            # noqa: BLE001 -- a hint only: the caller
        return None                              # falls back to the step's own words
    return shell_line(cmd, session, raws)


def _command(item, session):
    """The command that makes `item`, exact where the session gives it."""
    s = shlex.quote(session)
    if item == "report":
        return (f"python3 scripts/make_analysis_html.py --session {s} --out "
                f"{shlex.quote(os.path.join(session, 'output', REPORT_NAME))} (step 9)")
    if item == "methods":
        md = os.path.join(session, "output", METHODS_NAME)
        exact = _methods_command(session, md)
        return ((exact or f"python3 scripts/make_methods.py --raw <the raw files> --out "
                          f"{shlex.quote(md)} (the session has no raw-file list to name them)")
                + " (step 9d; session.py finalize also makes it)")
    if item == "reproducibility":
        exact = _bundle_command(session)
        return ((exact or f"python3 scripts/provenance.py --outdir "
                          f"{shlex.quote(os.path.join(session, 'output', 'reproducibility'))} "
                          f"--raw <the raw files> (the session's records could not be read)")
                + " (step 10; session.py finalize also makes it)")
    if item == "finalized":
        return f"python3 scripts/session.py finalize --dir {s} --zip (step 12)"
    return f"see SKILL.md for {shlex.quote(os.path.join(session, 'output'))}"


def finish_check(output_dir, need):
    """One entry per item `need` names (FINISH_NEEDS[tool]): {"item", "ok", "state", "why",
    "command", "warning"}. A pre-2.14.2 report passes with a warning (Review Focus 1)."""
    out = os.path.abspath(output_dir)
    session = session_of(out)
    items = []
    for item in need:
        e = {"item": item, "label": _ITEM_LABEL.get(item, item), "command": _command(item, session),
             "warning": None}
        if item == "report":
            state, why = skill_report_state(os.path.join(out, REPORT_NAME))
            e.update(ok=state in ("skill", "legacy_skill"), state=state, why=why)
            if state == "legacy_skill":
                e["warning"] = (f"WARNING: {REPORT_NAME} was {why}; it is accepted. Re-run "
                                "make_analysis_html.py to give it its record.")
        elif item == "methods":
            path = os.path.join(out, METHODS_NAME)
            ok = has_text(path)                      # an empty one is none (make_deposit's rule)
            e.update(ok=ok, state="present" if ok else ("empty" if os.path.isfile(path)
                                                        else "missing"),
                     why="present" if ok else ("output/methods.md is empty" if os.path.isfile(path)
                                               else "output/methods.md does not exist"))
        elif item == "reproducibility":
            # the bundle's record, a JSON object with something in it, describing the session
            # as it is now (bundle_state)
            state, why = bundle_state(out)
            e.update(ok=state == "present", state=state, why=why)
        elif item == "finalized":
            # a stamp counts only while what it stamped is unchanged (stamp_drift): a report
            # re-made, or a README edited, after finalize is not what was finalized
            rec, why = finalized_record(out)
            drift = stamp_drift(session, rec) if rec else []
            if rec and drift:
                e.update(ok=False, state="stale",
                         why=(f"finalized at {rec.get('finalized_at')}, but changed since: "
                              f"{', '.join(drift)} -- run session.py finalize again"))
            else:
                e.update(ok=rec is not None, state="finalized" if rec else "missing",
                         why=(f"finalized at {rec.get('finalized_at')}" if rec else why))
        else:
            e.update(ok=False, state="unknown", why=f"unknown finish item {item!r}")
        items.append(e)
    return items


def gap_line(label, why, command):
    """A gap as every refusal says it: what is missing, why, and the command that makes it."""
    return f"{label}: {why} -- make it with: {command}"


def finish_gaps(output_dir, need):
    """One plain sentence per missing item, each with the command that makes it ([] = none)."""
    return [gap_line(e["label"], e["why"], e["command"])
            for e in finish_check(output_dir, need) if not e["ok"]]


def finish_warnings(output_dir, need):
    return [e["warning"] for e in finish_check(output_dir, need) if e.get("warning")]


def refusal(tool, gaps):
    """The refusal every gate prints: each gap with its command, then the way past it."""
    return (f"[{tool}] refusing: the skill's finish steps are not done (SKILL.md golden rule 9):\n"
            + "".join(f"  - {g}\n" for g in gaps)
            + f"or re-run with {OVERRIDE_FLAG} \"<reason>\"")


def override_record(tool, gaps, reason):
    """{tool, missing, reason, at}: the caller records it (delivery.json `finish_override`,
    MANIFEST.txt's [OVERRIDE] line, podcast/podcast.json `finish_override`, FINALIZED.json)."""
    return {"tool": tool, "missing": list(gaps), "reason": " ".join(str(reason).split()),
            "at": _now()}


# Deliveries that carry no report of the session's, so its finish steps do not gate them: the
# raw files alone, and an interim delivery (the raw files and the search results; the report,
# Methods and bundle are owed -- delivery.json `owed` -- until a later no-de/analysis delivery).
UNGATED_DELIVERY_MODES = ("raw-only", "interim")


def delivery_finish_override(delivery):
    """The --override-finish a gated delivery was made under, or None (C2 errors_ux M1): deliver's
    own (delivery.json `finish_override`) first, else the one the finalize stamp it recorded was
    written under (`finalized.finish_override`). Either way the delivered package is NOT
    finalized, and every outward step after it says so (email-draft, bioshare send, status), as
    the Slack post does (notify_slack.announce_gate)."""
    d = delivery if isinstance(delivery, dict) else {}
    if d.get("mode") in UNGATED_DELIVERY_MODES:
        return None
    if isinstance(d.get("finish_override"), dict):
        return d["finish_override"]
    fin = d.get("finalized") if isinstance(d.get("finalized"), dict) else {}
    return fin.get("finish_override") if isinstance(fin.get("finish_override"), dict) else None


def delivery_finish_state(delivery):
    """A delivery record (delivery.json, from core_submission.py deliver) as the outward steps
    after it read it (bioshare send, email-draft): -> (ok, why). ok True: raw-only or interim
    (never gated: UNGATED_DELIVERY_MODES), or the session was finalized when it was delivered, or
    it was delivered under an override (delivery_finish_override: ranked FIRST -- a stamp
    recorded beside an override, or one written under an override, is not "finalized"; the why
    then starts NOT FINALIZED). ok None: a delivery.json from before 2.14.2, which does not say
    (accepted with a warning). ok False: delivered from a session that was not finalized."""
    d = delivery if isinstance(delivery, dict) else {}
    if d.get("mode") in UNGATED_DELIVERY_MODES:
        return True, f"{d['mode']} delivery: not gated"
    if "finalized" not in d and "finish_override" not in d:
        return None, ("delivery.json is from before skill 2.14.2: it does not say whether the "
                      "session was finalized")
    fo = delivery_finish_override(d)
    if fo:
        missing = [str(g).split(":", 1)[0] for g in (fo.get("missing") or [])]
        return True, ("NOT FINALIZED: delivered under --override-finish ("
                      + str(fo.get("reason") or "no reason recorded") + ")"
                      + (" without: " + "; ".join(missing) if missing else ""))
    if isinstance(d.get("finalized"), dict):
        return True, f"the session was finalized at {d['finalized'].get('finalized_at')}"
    return False, ("the session was not finalized when it was delivered (delivery.json "
                   "`finalized` is empty): run session.py finalize, then deliver again")
