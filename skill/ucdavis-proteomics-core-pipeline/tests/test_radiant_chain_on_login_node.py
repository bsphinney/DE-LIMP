#!/usr/bin/env python3
"""
On a login node, a multi-file Radiant search with no --sbatch routes to its per-file chain, as it
is meant to, instead of being refused inline (L8R-F10).

run_search.py decides `radiant_chain` (more than one file, SLURM here, no --no-parallel: a
per-file array plus one Fulcrum job, generated by radiant_parallel.py and submitted by the
orchestrator) -- but it decided it only AFTER the login-node refusal, whose condition looked at
the DIA-NN chain alone (`not use_parallel and not a.sbatch`). So the one route that never runs a
search here was refused as an inline search. The chain only writes job scripts, so it is exempt,
like the DIA-NN chain; a single-file Radiant search with no --sbatch is still refused.

Fakes only: sbatch is a stub on PATH (a login node), Radiant and DIA-NN are /bin/true, nothing is
submitted.
"""
import json
import os
import subprocess
import sys
import tempfile
import unittest

HERE = os.path.dirname(os.path.abspath(__file__))
SCRIPTS = os.path.join(os.path.dirname(HERE), "scripts")


def _write(path, text, mode=None):
    with open(path, "w") as fh:
        fh.write(text)
    if mode:
        os.chmod(path, mode)
    return path


def radiant_search(d, n_files, *extra):
    """run_search.py --engine radiant on a login node (a stub sbatch on PATH, no SLURM job)."""
    files = [_write(os.path.join(d, f"run{i}.mzML"), "<mzML/>") for i in range(n_files)]
    fasta = _write(os.path.join(d, "db.fasta"), ">sp|P1|X\nPEPTIDER\n")
    params = _write(os.path.join(d, "radiant.toml"), "# radiant config\n")
    tools = _write(os.path.join(d, "tools.json"), json.dumps(
        {"radiant": "/bin/true", "diann": "/bin/true", "radiant_runtime": "apptainer",
         "radiant_image": os.path.join(d, "radiant.sif")}))
    bundle = _write(os.path.join(d, "bundle.json"), json.dumps(
        {"engine": {"name": "radiant"}, "acquisition": "DIA"}))
    b = os.path.join(d, "bin")
    os.makedirs(b)
    _write(os.path.join(b, "sbatch"), "#!/bin/sh\necho 1\n", 0o755)
    env = {k: v for k, v in os.environ.items() if not k.startswith("SLURM_")}
    env.update(PATH=os.pathsep.join([b, os.path.dirname(sys.executable), "/usr/bin", "/bin"]),
               HPCCF_SLURM_BIN=os.path.join(d, "no_slurm"),
               UCD_HPC_CLUSTER_CONF=os.path.join(d, "no_cluster_file"))
    env.pop("PROTEOMICS_ON_COMPUTE", None)
    out = os.path.join(d, "out")
    return subprocess.run([sys.executable, os.path.join(SCRIPTS, "run_search.py"),
                           "--tools", tools, "--bundle", bundle, "--params", params,
                           "--fasta", fasta, "--out", out, "--files", *files,
                           "--engine", "radiant", "--threads", "8", *extra],
                          capture_output=True, text=True, env=env, cwd=d, timeout=240)


class RadiantChainOnALoginNode(unittest.TestCase):
    def test_a_multi_file_radiant_search_routes_to_its_chain(self):
        with tempfile.TemporaryDirectory() as d:
            p = radiant_search(d, 2)
            self.assertNotIn("REFUSING to run the search inline", p.stderr)
            self.assertIn("per-file array", p.stdout, p.stdout + p.stderr)

    def test_a_single_file_radiant_search_is_still_refused(self):
        """(pin) one file is not the chain: it would run here, so it is refused."""
        with tempfile.TemporaryDirectory() as d:
            p = radiant_search(d, 1)
            self.assertNotEqual(p.returncode, 0)
            self.assertIn("REFUSING to run the search inline", p.stderr)

    def test_no_parallel_is_still_refused(self):
        """(pin) --no-parallel asks for the serial search, which would run here."""
        with tempfile.TemporaryDirectory() as d:
            p = radiant_search(d, 2, "--no-parallel")
            self.assertNotEqual(p.returncode, 0)
            self.assertIn("REFUSING to run the search inline", p.stderr)


if __name__ == "__main__":
    unittest.main()
